#!/usr/bin/env python3
from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

try:
    from scipy import stats
except ImportError:  # pragma: no cover - fallback for minimal HPC environments.
    stats = None


METRICS = [
    "test_AUROC",
    "test_AUPRC",
    "test_R@5",
    "test_MRR",
    "test_image_R@5",
    "test_image_MRR",
    "test_brain_R@5",
    "test_brain_MRR",
]
DISPLAY_MODELS = {
    "roi_mlp": "ROI-MLP",
    "roi_transformer_gated": "Gated ROI Transformer",
    "roi_mlp_clip": "ROI-MLP+CLIP",
    "gated_roi_transformer_clip": "Gated ROI Transformer+CLIP",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Summarize LAION-fMRI external visual-ROI validation runs.")
    parser.add_argument(
        "--root",
        type=Path,
        default=Path("external_validation/laion_fmri/visual_roi_scalar4_laion/trained_external"),
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("external_validation/summary"),
    )
    return parser.parse_args()


def pm(mean: float, std: float) -> str:
    if pd.isna(std):
        return f"{mean:.4f}"
    return f"{mean:.4f}{{\\scriptstyle\\pm{std:.4f}}}"


def write_latex(path: Path, summary: pd.DataFrame) -> None:
    lines = [
        "% Auto-generated by scripts/summarize_laion_fmri_external_results.py",
        "% LAION-fMRI external visual-ROI validation; values are mean \\pm std over subject-pair x seed runs.",
    ]
    for _, row in summary.iterrows():
        model = DISPLAY_MODELS.get(str(row["model"]), str(row["model"]))
        values = [pm(float(row[f"{metric}_mean"]), float(row[f"{metric}_std"])) for metric in METRICS if f"{metric}_mean" in row]
        lines.append(f"{model} & $" + "$ & $".join(values) + r"$ \\")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def markdown_table(df: pd.DataFrame) -> str:
    columns = list(df.columns)
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join(["---"] * len(columns)) + " |",
    ]
    for _, row in df.iterrows():
        values = []
        for column in columns:
            value = row[column]
            if isinstance(value, float):
                values.append(f"{value:.4f}")
            else:
                values.append(str(value))
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def paired_tests(all_runs: pd.DataFrame) -> pd.DataFrame:
    models = sorted(all_runs["model"].unique())
    if {"roi_mlp_clip", "gated_roi_transformer_clip"}.issubset(models):
        baseline = "roi_mlp_clip"
        candidate = "gated_roi_transformer_clip"
        comparison = "Gated ROI Transformer+CLIP - ROI-MLP+CLIP"
    elif {"roi_mlp", "roi_transformer_gated"}.issubset(models):
        baseline = "roi_mlp"
        candidate = "roi_transformer_gated"
        comparison = "Gated ROI Transformer - ROI-MLP"
    else:
        return pd.DataFrame()

    rows = []
    for metric in METRICS:
        wide = all_runs.pivot_table(index=["pair", "seed"], columns="model", values=metric)
        wide = wide.dropna(subset=[baseline, candidate])
        if wide.empty:
            continue
        diff = wide[candidate] - wide[baseline]
        n = int(diff.shape[0])
        mean_diff = float(diff.mean())
        std_diff = float(diff.std(ddof=1)) if n > 1 else float("nan")
        sem = std_diff / math.sqrt(n) if n > 1 else float("nan")
        if stats is not None and n > 1:
            p_value = float(stats.ttest_rel(wide[candidate], wide[baseline]).pvalue)
            ci_delta = float(stats.t.ppf(0.975, n - 1) * sem)
        elif n > 1 and sem > 0:
            z = abs(mean_diff / sem)
            p_value = float(math.erfc(z / math.sqrt(2.0)))
            ci_delta = float(1.96 * sem)
        else:
            p_value = float("nan")
            ci_delta = float("nan")
        rows.append(
            {
                "comparison": comparison,
                "metric": metric,
                "n": n,
                "mean_diff": mean_diff,
                "std_diff": std_diff,
                "ci95_low": mean_diff - ci_delta,
                "ci95_high": mean_diff + ci_delta,
                "paired_p": p_value,
            }
        )
    return pd.DataFrame(rows)


def main() -> None:
    args = parse_args()
    rows = []
    for path in sorted(args.root.glob("*_*/**/summary.csv")):
        df = pd.read_csv(path)
        if df.empty:
            continue
        row = df.iloc[0].to_dict()
        row["pair"] = path.relative_to(args.root).parts[0]
        rows.append(row)
    if not rows:
        raise FileNotFoundError(f"No LAION-fMRI summary.csv files found under {args.root}")

    all_runs = pd.DataFrame(rows)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    all_runs.to_csv(args.out_dir / "laion_fmri_visual_roi_all_runs.csv", index=False)

    grouped_rows = []
    for model, group in all_runs.groupby("model"):
        row = {"model": model, "n": len(group)}
        for metric in METRICS:
            if metric in group:
                row[f"{metric}_mean"] = group[metric].mean()
                row[f"{metric}_std"] = group[metric].std(ddof=1)
        grouped_rows.append(row)
    summary = pd.DataFrame(grouped_rows).sort_values("model")
    summary.to_csv(args.out_dir / "laion_fmri_visual_roi_summary.csv", index=False)
    tests = paired_tests(all_runs)
    tests.to_csv(args.out_dir / "laion_fmri_visual_roi_pairwise_tests.csv", index=False)
    write_latex(args.out_dir / "laion_fmri_visual_roi_latex.txt", summary)
    test_text = ""
    if not tests.empty:
        test_text = (
            "\n\nPaired tests compare Gated ROI Transformer against ROI-MLP over matched subject-pair × seed runs.\n\n"
            + markdown_table(tests)
        )
    (args.out_dir / "laion_fmri_visual_roi_summary.md").write_text(
        "# LAION-fMRI External Visual-ROI Validation\n\n"
        "Trial-wise public LAION-fMRI beta maps were summarized with public visual ROI masks, padded to the same 180-token interface, and evaluated with cross-subject same-image retrieval. Values are mean ± std over subject-pair × seed runs.\n\n"
        + markdown_table(summary)
        + test_text
        + "\n\nLaTeX rows are available in `laion_fmri_visual_roi_latex.txt`.\n",
        encoding="utf-8",
    )
    print({"all_runs": len(all_runs), "summary": str(args.out_dir / "laion_fmri_visual_roi_summary.csv")})


if __name__ == "__main__":
    main()
